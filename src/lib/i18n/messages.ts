export function t(locale: Locale, key: string, parameters: Record<string, string | number> = {}): string {
  const template = messages[locale][key] ?? messages.en[key] ?? key;
  return Object.entries(parameters).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function localeHref(basePath: string, locale: Locale): string {
  const base = basePath === '/' ? '' : basePath.replace(/\/$/, '');
  return `${base}/${locale}/`;
}

export function missingMessageKeys(locale: Locale): string[] {
  return Object.keys(messages.en).filter((key) => !(key in messages[locale]));
}
